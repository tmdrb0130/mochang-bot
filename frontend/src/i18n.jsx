// 새 문구를 추가할 때: ko 에 넣고 en·zh·ja 에도 같은 키를 넣는다. 빠진 키는 ko 로 떨어진다.
import { createContext, useContext } from "react";

export const LANGS = [
  { id: "ko", label: "한국어" },
  { id: "en", label: "English" },
  { id: "zh", label: "中文" },
  { id: "ja", label: "日本語" },
];
export const LANG_KEY = "modoo-writer-lang-v1";
// 번역 프롬프트에 넣는 언어 이름(백엔드 LANG_NAMES 와 코드가 같다). 화면의 "영어 번역" 같은 머리말에도 쓴다.
export const LANG_NAMES = { ko: "한국어", en: "English", zh: "中文", ja: "日本語" };

const isLang = (id) => LANGS.some((l) => l.id === id);

/** 저장된 선택 → 없으면 브라우저 언어 → 없으면 ko. */
export function loadLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (isLang(saved)) return saved;
  } catch { /* 접근 차단 */ }
  const nav = String((typeof navigator !== "undefined" && navigator.language) || "").toLowerCase().split("-")[0];
  return isLang(nav) ? nav : "ko";
}

export function saveLang(id) {
  try { localStorage.setItem(LANG_KEY, id); } catch { /* 접근 차단 — 이번 탭에서만 유지 */ }
}

